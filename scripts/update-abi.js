const fs = require("fs");
const path = require("path");

const artifactPath = path.join(__dirname, "..", "artifacts", "contracts", "MultiPollVoting.sol", "MultiPollVoting.json");
const configPath = path.join(__dirname, "..", "frontend", "contract-config.js");

const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
const current = fs.readFileSync(configPath, "utf8");
const match = current.match(/CONTRACT_ADDRESS = "(0x[a-fA-F0-9]+)"/);
const address = match ? match[1] : "0x55e9f1374B96FCDC1DdeE275F8F3BdBAa14cC98b";

const content = `// Auto-generated by scripts/deploy.js
export const CONTRACT_ADDRESS = "${address}";

export const CONTRACT_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;

fs.writeFileSync(configPath, content, "utf8");
console.log("Updated frontend/contract-config.js successfully with", artifact.abi.length, "ABI definitions.");
