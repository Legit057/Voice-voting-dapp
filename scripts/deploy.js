const { ethers, artifacts } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("Starting deployment of MultiPollVoting...");

  const MultiPollVoting = await ethers.getContractFactory("MultiPollVoting");
  const voting = await MultiPollVoting.deploy({
    gasLimit: 14500000,
    maxFeePerGas: ethers.parseUnits("0.5", "gwei"),
    maxPriorityFeePerGas: ethers.parseUnits("0.05", "gwei"),
  });
  await voting.waitForDeployment();

  const contractAddress = await voting.getAddress();
  console.log("----------------------------------------------------");
  console.log("MultiPollVoting deployed successfully!");
  console.log("Contract Address:", contractAddress);
  console.log("----------------------------------------------------");

  // Read the compiled artifact
  const contractArtifact = await artifacts.readArtifact("MultiPollVoting");

  // Destination folder and file
  const frontendDir = path.join(__dirname, "..", "frontend");
  const configFilePath = path.join(frontendDir, "contract-config.js");

  // Ensure frontend directory exists
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  // Generate frontend/contract-config.js exporting CONTRACT_ADDRESS and CONTRACT_ABI
  const configContent = `// Auto-generated by scripts/deploy.js
export const CONTRACT_ADDRESS = "${contractAddress}";

export const CONTRACT_ABI = ${JSON.stringify(contractArtifact.abi, null, 2)};
`;

  fs.writeFileSync(configFilePath, configContent, "utf8");
  console.log(`Saved contract configuration to ${configFilePath}`);
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
